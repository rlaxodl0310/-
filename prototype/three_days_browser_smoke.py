"""Complete three days while people are encountered through their own activities."""
from playwright.sync_api import sync_playwright

with sync_playwright() as p:
    browser = p.chromium.launch(headless=True, executable_path='/usr/bin/chromium')
    for path in ['/prototype/', '/demo/campus-demo.html']:
        page = browser.new_page(viewport={'width': 1440, 'height': 1000})
        errors = []
        page.on('pageerror', lambda error: errors.append(str(error)))
        page.goto('http://127.0.0.1:8000' + path)
        page.get_by_role('button', name='메뉴', exact=True).click()
        page.get_by_role('button', name='친한 동료', exact=True).click()
        page.get_by_role('button', name='하던 일을 계속하며 지나간다.').click()
        page.get_by_role('button', name='오후 활동 고르기').click()
        page.get_by_role('button', name='자유 탐색 1시간').click()
        page.get_by_role('button', name='이 활동 진행').click()
        page.get_by_role('button', name='하루 마무리하기').click()
        page.get_by_role('button', name='2일차 시작하기').click()
        page.get_by_role('button', name='학생회관 들어가기').click()
        assert '제목' in page.locator('.lead').inner_text()
        page.locator('[data-action="encounter"][data-value="engage"]').click()
        page.get_by_role('button', name='다른 이야기로 넘어가기').click()
        page.get_by_role('button', name='내일은 어떤 일정이에요?').click()
        page.get_by_role('button', name='내일 같이 하기로 약속한다').click()
        page.get_by_role('button', name='← 대화 마치기').click()
        page.get_by_role('button', name='다른 장소로 이동').click()
        page.get_by_role('button', name='대학가 카페 찾아가기').click()
        assert '빈자리' in page.locator('.lead').inner_text()
        page.locator('[data-action="encounter"][data-value="engage"]').click()
        page.get_by_role('button', name='다른 이야기로 넘어가기').click()
        page.get_by_role('button', name='내일은 어떤 일정이에요?').click()
        page.get_by_role('button', name='내일 같이 하기로 약속한다').click()
        page.get_by_role('button', name='활동 살펴보기').click()
        page.get_by_role('button', name='개인 음악 작업 2시간').click()
        page.get_by_role('button', name='이 활동 진행').click()
        page.get_by_role('button', name='학생회관으로 돌아간다').click()
        page.locator('[data-action="encounter"][data-value="engage"]').click()
        page.get_by_role('button', name='다른 이야기로 넘어가기').click()
        page.get_by_role('button', name='오늘은 어땠어요? 아까 좀 바빠 보이던데.').click()
        assert '소율' in page.locator('blockquote').inner_text()
        page.get_by_role('button', name='← 대화 마치기').click()
        page.get_by_role('button', name='하루 마무리하기').click()
        page.get_by_role('button', name='3일차 시작하기').click()
        page.get_by_role('button', name='메뉴', exact=True).click()
        page.locator('[data-action="save"][data-value="2"]').click()
        page.get_by_role('button', name='← 뒤로').click()
        page.get_by_role('button', name='학생회관 들어가기').click()
        page.get_by_role('button', name='하던 일을 계속하며 지나간다.').click()
        page.get_by_role('button', name='오후 활동 고르기').click()
        assert page.get_by_role('button', name='연결 통로로 장비 운반 돕기', exact=False).is_enabled()
        page.get_by_role('button', name='공연 리허설 참여 2시간').click()
        assert page.get_by_text('차여경과 한 전시 준비 약속을 지키지 못하게 됩니다.', exact=False).is_visible()
        page.get_by_role('button', name='이 활동 진행').click()
        page.get_by_role('button', name='학생회관으로 돌아간다').click()
        page.locator('[data-action="encounter"][data-value="engage"]').click()
        assert '인원에 넣어' in page.locator('blockquote').inner_text()
        page.get_by_role('button', name='← 대화 마치기').click()
        page.get_by_role('button', name='3일의 기록 보기').click()
        assert page.get_by_text('1일차 · 자유 탐색', exact=True).is_visible()
        assert page.get_by_text('3일차 · 공연 리허설 참여', exact=True).is_visible()
        page.get_by_role('button', name='← 뒤로').click()
        page.get_by_role('button', name='메뉴', exact=True).click()
        page.locator('[data-action="load"][data-value="2"]').click()
        assert page.get_by_text('김태이 · 3일차 · 토요일 · 오후', exact=True).is_visible()
        assert not errors, errors
        print(path + ': three-day incidental encounters, invitations, route unlock, conflict and save/load passed.')
        page.close()
    browser.close()
