"""Voluntary membership, activity offers and NPC initiative in both browser builds."""
from flow_browser_helpers import finish_morning
from flow_browser_helpers import open_map, visit_place, open_schedule, choose_activity, open_recruitment, end_day, go_campus
from playwright.sync_api import sync_playwright
import os
base=os.environ.get('CAMPUS_TEST_URL','http://127.0.0.1:8000')
with sync_playwright() as p:
    browser=p.chromium.launch(headless=True,executable_path='/usr/bin/chromium')
    for path in ['/prototype/','/demo/campus-demo.html']:
        page=browser.new_page(viewport={'width':390,'height':844})
        page.set_default_timeout(7000)
        errors=[];page.on('pageerror',lambda error:errors.append(str(error)))
        page.goto(base+path)
        finish_morning(page)
        open_recruitment(page)
        assert page.locator('[data-action="readPost"][data-value$="-recruit"]').count()==3
        page.locator('[data-action="readPost"][data-value="football-recruit"]').click()
        page.get_by_role('button',name='이 글의 모집 안내를 자세히 읽는다.',exact=True).click()
        page.get_by_role('button',name='이 동아리에 가입하기',exact=True).click()
        assert '가입 중입니다' in page.locator('.page').inner_text()
        page.get_by_role('button',name='약속과 일정 보기',exact=True).click()
        football=page.locator('article.list').filter(has=page.locator('strong',has_text='축구 동아리 체험 훈련'))
        assert '응답 전' in football.inner_text()
        football.get_by_role('button',name='수락하기',exact=True).click()
        assert '참석 예정' in football.inner_text()
        page.get_by_role('button',name='← 뒤로',exact=True).click()
        page.get_by_role('button',name='← 뒤로',exact=True).click()
        go_campus(page)
        page.get_by_role('button',name='메뉴',exact=True).click()
        page.get_by_role('button',name='저장',exact=True).first.click()
        saved=page.evaluate("JSON.parse(localStorage.getItem('campus.slot.1'))")
        assert 'football' in saved['memberships'] and not saved['memberships'].get('volunteer')
        assert saved['contacts']=={}  # club joining doesn't invent football cast or volunteer friends
        page.get_by_role('button',name='친한 동료',exact=True).click()
        page.get_by_role('button',name='하던 일을 계속하며 지나간다.').click()
        page.get_by_role('button',name='약속 제안 3개 확인',exact=True).click()
        personal=page.locator('article.list').filter(has=page.locator('strong',has_text='잠깐 쉬며 이야기하기'))
        assert '상대가 먼저 제안' in personal.inner_text()
        personal.get_by_role('button',name='수락하기',exact=True).click()
        assert '참석 예정' in personal.inner_text()
        soyul=page.locator('article.list').filter(has=page.locator('strong',has_text='사진 이야기 이어가기'))
        assert '겹칠 수 있습니다' in soyul.inner_text()
        soyul.get_by_role('button',name='정중히 거절하기',exact=True).click()
        assert '거절함' in soyul.inner_text()
        personal.get_by_role('button',name='미리 연락해 취소',exact=True).click()
        assert '미리 취소함' in personal.inner_text()
        # Fresh relationship example: accept and actually keep an NPC-originated meeting.
        page.get_by_role('button',name='← 뒤로',exact=True).click()
        page.get_by_role('button',name='← 뒤로',exact=True).click()
        go_campus(page)
        page.get_by_role('button',name='메뉴',exact=True).click()
        page.get_by_role('button',name='친한 동료',exact=True).click()
        page.get_by_role('button',name='하던 일을 계속하며 지나간다.').click()
        page.get_by_role('button',name='약속 제안 3개 확인',exact=True).click()
        page.locator('[data-appointment-id="npc:seoyeon:1"]').get_by_role('button',name='수락하기',exact=True).click()
        page.get_by_role('button',name='← 뒤로',exact=True).click()
        page.get_by_role('button',name='← 뒤로',exact=True).click()
        choose_activity(page, 'rehearsal')
        page.get_by_role('button',name='이 활동 진행',exact=True).click()
        end_day(page)
        page.get_by_role('button',name='2일차 시작하기',exact=True).click()
        open_map(page)
        page.get_by_role('button',name='대학가 카페 찾아가기',exact=True).click()
        assert '약속이 떠오른다' in page.locator('.lead').inner_text()
        page.locator('[data-action="encounter"][data-value="engage"]').click()
        page.get_by_role('button',name='← 대화 마치기',exact=True).click()
        page.get_by_role('button',name='← 뒤로',exact=True).click()
        page.get_by_role('button',name='휴대폰',exact=True).click()
        page.get_by_role('button',name='일정',exact=True).click()
        assert '지킴' in page.locator('[data-appointment-id="npc:seoyeon:1"]').inner_text()
        assert page.evaluate('document.documentElement.scrollWidth<=innerWidth')
        assert not errors,errors
        page.close()
    browser.close()
print('Appointment and club UI smoke passed: both builds')
