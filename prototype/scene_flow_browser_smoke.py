"""The playable path is scene -> local action -> consequence, with an optional organizer."""
from playwright.sync_api import sync_playwright
import os
base=os.environ.get('CAMPUS_TEST_URL','http://127.0.0.1:8000')
with sync_playwright() as p:
    browser=p.chromium.launch(headless=True,executable_path='/usr/bin/chromium')
    for path in ['/prototype/','/demo/campus-demo.html']:
        page=browser.new_page(viewport={'width':390,'height':844})
        page.set_default_timeout(7000)
        errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
        page.goto(base+path)
        assert page.locator('.prompt button').count()==2
        for old in ['오후 활동 고르기','동아리 살펴보기','다른 장소로 이동']:
            assert not page.get_by_role('button',name=old,exact=True).count()
        if path=='/prototype/':page.screenshot(path='/tmp/scene-opening.png',full_page=True)
        page.get_by_role('button',name='게시판에 붙은 종이를 가까이서 읽는다.',exact=True).click()
        assert page.get_by_role('button',name='봉사단 모집 안내를 자세히 읽는다.',exact=True).is_visible()
        page.get_by_role('button',name='봉사단 모집 안내를 자세히 읽는다.',exact=True).click()
        page.get_by_role('button',name='이 동아리에 가입하기',exact=True).click()
        assert '가입 중입니다' in page.locator('.page').inner_text()
        page.get_by_role('button',name='← 뒤로',exact=True).click()
        page.get_by_role('button',name='물품을 옮기는 학생회관 안쪽으로 들어간다.',exact=True).click()
        assert '영수증' in page.locator('.lead').inner_text()
        page.get_by_role('button',name='하던 일을 계속하며 지나간다.',exact=True).click()
        page.get_by_role('button',name='쌓인 물품 상자 쪽으로 가서 준비를 도울지 살펴본다.',exact=True).click()
        page.get_by_role('button',name='아직 시작하지 않고 돌아간다.',exact=True).click()
        assert page.get_by_role('button',name='게시판 쪽으로 걸어간다',exact=True).is_visible()
        page.get_by_role('button',name='쌓인 물품 상자 쪽으로 가서 준비를 도울지 살펴본다.',exact=True).click()
        page.get_by_role('button',name='이 활동 진행',exact=True).click()
        page.get_by_role('button',name='하루 마무리하기',exact=True).click()
        page.get_by_role('button',name='2일차 시작하기',exact=True).click()
        assert '곡의 메모' in page.locator('.prompt').inner_text()
        page.get_by_role('button',name='떠오른 가사를 잊기 전에 자취방에서 데모를 다듬는다.',exact=True).click()
        page.get_by_role('button',name='이 활동 진행',exact=True).click()
        page.get_by_role('button',name='하루 마무리하기',exact=True).click()
        page.get_by_role('button',name='3일차 시작하기',exact=True).click()
        page.get_by_role('button',name='휴대폰',exact=True).click()
        page.get_by_role('button',name='메시지',exact=True).click()
        page.get_by_role('button',name='← 뒤로',exact=True).click()
        page.get_by_role('button',name='← 뒤로',exact=True).click()
        page.get_by_role('button',name='사진 전시 안내가 붙은 학생회관으로 간다.',exact=True).click()
        page.get_by_role('button',name='하던 일을 계속하며 지나간다.',exact=True).click()
        page.get_by_role('button',name='접한 안내가 마음에 걸린다. 다른 건물의 안내도 확인한다.',exact=True).click()
        page.get_by_role('button',name='이 활동 진행',exact=True).click()
        assert '같은 원인인지' in page.locator('.lead').inner_text()
        page.get_by_role('button',name='건물 밖으로 나와 주변을 둘러본다.',exact=True).click()
        page.get_by_role('button',name='메뉴',exact=True).click()
        page.get_by_role('button',name='저장',exact=True).first.click()
        saved=page.evaluate("JSON.parse(localStorage.getItem('campus.slot.1'))")
        assert saved['flow']['seen']['board'] and saved['memberships']['volunteer']
        assert page.evaluate('document.documentElement.scrollWidth<=innerWidth')
        assert not errors,errors
        page.close()
    browser.close()
print('Scene-led three-day browser flow passed: both builds')
