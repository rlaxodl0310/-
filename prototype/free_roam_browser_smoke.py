"""Arrive, choose any destination, use the phone voluntarily, and do multiple tasks before going home."""
from flow_browser_helpers import finish_morning
from playwright.sync_api import sync_playwright
import os
base=os.environ.get('CAMPUS_TEST_URL','http://127.0.0.1:8000')
with sync_playwright() as p:
    browser=p.chromium.launch(headless=True,executable_path='/usr/bin/chromium')
    for path in ['/prototype/','/demo/campus-demo.html']:
        page=browser.new_page(viewport={'width':390,'height':844});page.set_default_timeout(7000)
        errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
        page.goto(base+path)
        finish_morning(page)
        assert '공강' in page.locator('.prompt').inner_text()
        assert '커뮤니티' not in page.locator('.prompt').inner_text()
        assert not page.locator('.prompt [data-action="select"]').count()
        if path=='/prototype/':page.screenshot(path='/tmp/free-campus-arrival.png',full_page=True)
        page.get_by_role('button',name='도서관으로 이어지는 길을 따라간다.',exact=True).click()
        page.get_by_role('button',name='반납대와 자료실을 둘러본다',exact=True).click()
        before=page.locator('.lead').inner_text()
        assert not page.locator('[data-action="openCommunity"]').count()
        page.get_by_role('button',name='휴대폰',exact=True).click()
        page.get_by_role('button',name='학내 커뮤니티',exact=True).click()
        assert page.get_by_role('heading',name='캠퍼스톡',exact=True).is_visible()
        page.get_by_role('button',name='← 뒤로',exact=True).click()
        page.get_by_role('button',name='← 뒤로',exact=True).click()
        assert page.locator('.lead').inner_text()==before
        page.get_by_role('button',name='돌아가기 전에 주변 길을 조금 더 알아둔다.',exact=True).click()
        assert '16:00 시작' not in page.locator('.page').inner_text()
        page.get_by_role('button',name='이 활동 진행',exact=True).click()
        page.get_by_role('button',name='건물 밖으로 나와 주변을 둘러본다.',exact=True).click()
        assert '오후' in page.locator('.badge').inner_text()
        page.get_by_role('button',name='자유관 쪽으로 걸어간다.',exact=True).click()
        page.get_by_role('button',name='하던 일을 계속하며 지나간다.',exact=True).click()
        page.get_by_role('button',name='예술동 쪽으로 걸어간다.',exact=True).click()
        page.get_by_role('button',name='연습실에 들러 합주할 수 있을지 살펴본다.',exact=True).click()
        page.get_by_role('button',name='이 활동 진행',exact=True).click()
        page.get_by_role('button',name='건물 밖으로 나와 주변을 둘러본다.',exact=True).click()
        assert '16:30' in page.locator('.badge').inner_text() and '오후' in page.locator('.badge').inner_text()
        page.get_by_role('button',name='휴대폰',exact=True).click()
        page.get_by_role('button',name='일정',exact=True).click()
        assert not page.locator('[data-routine]').count()
        assert '자유 탐색' in page.locator('.page').inner_text() and '합주' in page.locator('.page').inner_text()
        page.get_by_role('button',name='← 뒤로',exact=True).click()
        page.get_by_role('button',name='← 뒤로',exact=True).click()
        page.get_by_role('button',name='오늘은 집으로 돌아간다.',exact=True).click()
        page.get_by_role('button',name='아직 학교에 더 머문다.',exact=True).click()
        assert page.locator('.explore').is_visible()
        page.get_by_role('button',name='오늘은 집으로 돌아간다.',exact=True).click()
        page.get_by_role('button',name='오늘은 귀가한다.',exact=True).click()
        page.get_by_role('button',name='2일차 시작하기',exact=True).click()
        assert '곧 수업이 시작된다' in page.locator('.prompt').inner_text()
        page.get_by_role('button',name='메뉴',exact=True).click()
        page.get_by_role('button',name='저장',exact=True).first.click()
        saved=page.evaluate("JSON.parse(localStorage.getItem('campus.slot.1'))")
        assert len(saved['dayHistory'][0]['activities'])==2 and saved['freeDay']['completed']==[]
        assert saved['appointments']==[]
        assert page.evaluate('document.documentElement.scrollWidth<=innerWidth')
        assert not errors,errors
        page.close()
    browser.close()
print('Free campus and phone-only community browser smoke passed: both builds')
